/** Select one option from a choice reward group (calls RPC select_reward_option) */
export function useSelectRewardOption() {
  const qc = useQueryClient();
  return useMutation({
    mutationFn: async (params: {
      rewardId: number;
      optionSlug: string;
      customerId: number;
    }) => {
      const { data, error } = await (supabase as any).rpc("select_reward_option", {
        p_reward_id:   params.rewardId,
        p_option_slug: params.optionSlug,
        p_customer_id: params.customerId,
      });
      if (error) throw error;
      if (!data?.success) throw new Error(data?.error || "No se pudo actualizar el premio");
      return data as { success: boolean; selected_option?: string; reward_name?: string; group_id?: string; error?: string };
    },
    onSuccess: (_data, vars) => {
      qc.invalidateQueries({ queryKey: ["customer_loyalty", vars.customerId] });
      qc.invalidateQueries({ queryKey: ["available_loyalty_rewards", vars.customerId] });
    },
  });
}

